// Color themes, selectable on the title screen.
// Each theme is 4 background palettes of 4 entries: { backdrop, dark, medium, light }.
// Palette n colors the blocks of color n+1. Palette 3 is also the interface palette:
// text, the two frames and the playfield floor all use it, and its dark shade (the
// second entry) IS the floor colour.
// The first entry of every palette is the shared backdrop color and must be identical.
// NES color numbers: $0x dark, $1x medium, $2x light, $3x pale; columns 1..C are hues.
